type application struct {
	store *stateStore
	views *jet.Set
}

func newApplicationFromViews(files fs.FS) (*application, error) {
	set := jet.NewSet(viewLoader{files: files}, jet.WithTemplateNameExtensions([]string{"", ".jet"}))
	err := fs.WalkDir(files, ".", func(viewPath string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() || !strings.HasSuffix(viewPath, ".jet") {
			return nil
		}
		if _, err := set.GetTemplate(viewPath); err != nil {
			return fmt.Errorf("parse view %s: %w", viewPath, err)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	return &application{store: newStateStore(), views: set}, nil
}

func newApplication() *application {
	files, err := fs.Sub(viewFiles, "web/views")
	if err != nil {
		panic(err)
	}
	application, err := newApplicationFromViews(files)
	if err != nil {
		panic(err)
	}
	return application
}

func (a *application) render(name string, data any) (bytes.Buffer, error) {
	var output bytes.Buffer
	template, err := a.views.GetTemplate(name)
	if err != nil {
		return output, err
	}
	err = template.Execute(&output, nil, data)
	return output, err
}

func (a *application) handler() http.Handler {
	mux := http.NewServeMux()
	mux.HandleFunc("GET /", a.index)
	mux.HandleFunc("GET /metrics", a.metrics)
	mux.HandleFunc("POST /toggle-service", a.toggleService)
	mux.HandleFunc("GET /healthz", func(w http.ResponseWriter, _ *http.Request) { _, _ = w.Write([]byte("ok")) })
	mux.Handle("GET /static/", http.StripPrefix("/static/", http.FileServer(http.Dir(filepath.Join("web", "static")))))
	return mux
}

func serviceViews(services []service, outOfBand bool, lang language) []serviceView {
	localized := messageTable[lang]
	views := make([]serviceView, len(services))
	for i, current := range services {
		views[i] = serviceView{Service: current, OutOfBand: outOfBand, Messages: localized, Language: lang, StatusLabel: localizedStatus(current.Status, lang), LogsTitle: fmt.Sprintf(localized["logs title"], current.Name), HelpTitle: fmt.Sprintf(localized["help title"], current.Name), HelpLabel: fmt.Sprintf(localized["help label"], current.Name)}
	}
	return views
}

func (a *application) index(w http.ResponseWriter, r *http.Request) {
	lang, fromQuery := resolveLanguage(r)
	if fromQuery {
		persistLanguageCookie(w, lang)
	}
	localized := messageTable[lang]
	output, err := a.render("pages/index.jet", pageView{Language: lang, Messages: localized, Services: serviceViews(a.store.snapshot(), false, lang)})
	if err != nil {
		http.Error(w, "template rendering failed", http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	_, _ = w.Write(output.Bytes())
}

func (a *application) renderFragment(viewPath string, view serviceView) (string, error) {
	output, err := a.render(viewPath, view)
	return output.String(), err
}

func (a *application) renderTick(lang language, services []service, lastStatus map[string]serviceStatus) (string, error) {
	var output strings.Builder
	for _, current := range services {
		view := serviceViews([]service{current}, true, lang)[0]
		metrics, err := a.renderFragment("fragments/metrics.jet", view)
		if err != nil {
			return "", err
		}
		output.WriteString(metrics)
		logs, err := a.renderFragment("fragments/logs.jet", view)
		if err != nil {
			return "", err
		}
		output.WriteString(logs)
		if lastStatus[current.ID] != current.Status {
			status, err := a.renderFragment("fragments/status.jet", view)
			if err != nil {
				return "", err
			}
			output.WriteString(status)
		}
	}
	return output.String(), nil
}

func writeSSEFrame(w io.Writer, html string) error {
	if _, err := fmt.Fprint(w, "event: metrics\n"); err != nil {
		return err
	}
	for _, line := range bytes.Split([]byte(html), []byte("\n")) {
		if _, err := fmt.Fprintf(w, "data: %s\n", line); err != nil {
			return err
		}
	}
	_, err := fmt.Fprint(w, "\n")
	return err
}

func (a *application) metrics(w http.ResponseWriter, r *http.Request) {
	lang, fromQuery := resolveLanguage(r)
	if fromQuery {
		persistLanguageCookie(w, lang)
	}
	w.Header().Set("Content-Type", "text/event-stream")
	w.Header().Set("Cache-Control", "no-cache")
	w.Header().Set("Connection", "keep-alive")
	w.Header().Set("X-Accel-Buffering", "no")
	w.Header().Add("Vary", "Accept-Encoding")
	flusher, ok := w.(http.Flusher)
	if !ok {
		http.Error(w, "streaming unsupported", http.StatusInternalServerError)
		return
	}
	var output io.Writer = w
	var compressor *gzip.Writer
	if strings.Contains(strings.ToLower(r.Header.Get("Accept-Encoding")), "gzip") {
		w.Header().Set("Content-Encoding", "gzip")
		compressor = gzip.NewWriter(w)
		defer compressor.Close()
		output = compressor
	}
	lastStatus := make(map[string]serviceStatus)
	flush := func() {
		if compressor != nil {
			_ = compressor.Flush()
		}
		flusher.Flush()
	}
	writeFrame := func() bool {
		services := a.store.snapshot()
		html, err := a.renderTick(lang, services, lastStatus)
		if err != nil || writeSSEFrame(output, html) != nil {
			return false
		}
		for _, current := range services {
			lastStatus[current.ID] = current.Status
		}
		flush()
		return true
	}
	if !writeFrame() {
		return
	}
	tick := time.NewTicker(2 * time.Second)
	defer tick.Stop()
	heartbeat := time.NewTicker(15 * time.Second)
	defer heartbeat.Stop()
	for {
		select {
		case <-r.Context().Done():
			return
		case <-tick.C:
			if !writeFrame() {
				return
			}
		case <-heartbeat.C:
			if _, err := fmt.Fprint(output, ": keep-alive\n\n"); err != nil {
				return
			}
			flush()
		}
	}
}

func (a *application) toggleService(w http.ResponseWriter, r *http.Request) {
	lang, fromQuery := resolveLanguage(r)
	if fromQuery {
		persistLanguageCookie(w, lang)
	}
	if value := r.FormValue("lang"); value == string(languageSpanish) || value == string(languageEnglish) {
		if r.URL.Query().Get("lang") == "" {
			lang = language(value)
		}
	}
	localized := messageTable[lang]
	current, ok := a.store.toggle(r.FormValue("id"))
	if !ok {
		http.Error(w, "unknown service", http.StatusNotFound)
		return
	}
	statusLabel := localizedStatus(current.Status, lang)
	adverbialStatus := map[serviceStatus]string{statusOnline: "online", statusOffline: "offline"}[current.Status]
	if lang == languageSpanish {
		adverbialStatus = map[serviceStatus]string{statusOnline: "en línea", statusOffline: "desconectado"}[current.Status]
	}
	trigger := asciiJSON(map[string]map[string]string{"pulse-toggled": {
		"id": current.ID, "name": current.Name, "status": string(current.Status), "message": fmt.Sprintf(localized["toast message"], current.Name, adverbialStatus), "statusLabel": statusLabel,
	}})
	w.Header().Set("HX-Trigger", trigger)
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	output, err := a.render("fragments/card-surface.jet", serviceViews([]service{current}, false, lang)[0])
	if err != nil {
		http.Error(w, "template rendering failed", http.StatusInternalServerError)
		return
	}
	_, _ = w.Write(output.Bytes())
}

func expectedAssets() []string {
	return []string{"bootstrap.min.css", "bootstrap.bundle.min.js", "htmx.min.js", "htmx-ext-sse.min.js", "alpine.module.esm.js"}
}

func verifyAssets(staticDir string) error {
	cwd, _ := os.Getwd()
	for _, name := range expectedAssets() {
		assetPath := filepath.Join(staticDir, "vendor", name)
		if _, err := os.Stat(assetPath); err != nil {
			resolvedPath, absErr := filepath.Abs(assetPath)
			if absErr != nil {
				resolvedPath = assetPath
			}
			return fmt.Errorf("missing vendor asset %s at %s (working directory %s); run npm install && npm run sync:assets", name, resolvedPath, cwd)
		}
	}
	return nil
}

func run(ctx context.Context, addr string) error {
	staticDir := filepath.Join("web", "static")
	if err := verifyAssets(staticDir); err != nil {
		return err
	}
	files, err := fs.Sub(viewFiles, "web/views")
	if err != nil {
		return err
	}
	application, err := newApplicationFromViews(files)
	if err != nil {
		return err
	}
	server := &http.Server{Addr: addr, Handler: application.handler()}
	go func() {
		ticker := time.NewTicker(2 * time.Second)
		defer ticker.Stop()
		for {
			select {
			case <-ticker.C:
				application.store.advanceMetrics()
			case <-ctx.Done():
				return
			}
		}
	}()
	go func() {
		<-ctx.Done()
		_ = server.Shutdown(context.Background())
	}()
	slog.Info("devops-pulse listening", "addr", addr)
	return server.ListenAndServe()
}

func main() {
	addr := flag.String("addr", ":8080", "HTTP listen address")
	flag.Parse()
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if err := run(ctx, *addr); err != nil && err != http.ErrServerClosed {
		slog.Error("server stopped", "error", err)
		os.Exit(1)
	}
}
